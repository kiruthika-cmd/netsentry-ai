"""
NetSentry AI - Database Connection and Initialization Module
Manages SQLite connection lifecycle, safe parameterized execution, and schema creation.
"""

import sqlite3
import logging
from pathlib import Path
from contextlib import contextmanager

logger = logging.getLogger("netsentry.database")

SCHEMA_SQL = """
-- Packets table: records analyzed packets (live and PCAP)
CREATE TABLE IF NOT EXISTS packets (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    timestamp DATETIME DEFAULT CURRENT_TIMESTAMP,
    src_ip TEXT NOT NULL,
    dst_ip TEXT NOT NULL,
    src_port INTEGER,
    dst_port INTEGER,
    protocol TEXT NOT NULL,
    length INTEGER NOT NULL,
    info TEXT,
    is_suspicious INTEGER DEFAULT 0,
    anomaly_score REAL DEFAULT 0.0,
    source_type TEXT DEFAULT 'live'
);

-- Alerts table: security detections generated by rules or ML
CREATE TABLE IF NOT EXISTS alerts (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    alert_id TEXT UNIQUE NOT NULL,
    timestamp DATETIME DEFAULT CURRENT_TIMESTAMP,
    src_ip TEXT NOT NULL,
    dst_ip TEXT NOT NULL,
    detection_type TEXT NOT NULL, -- 'rule' or 'ml'
    rule_name TEXT NOT NULL,
    description TEXT NOT NULL,
    severity TEXT NOT NULL,       -- 'Low', 'Medium', 'High', 'Critical'
    risk_score INTEGER NOT NULL,  -- 0 - 100
    explanation TEXT NOT NULL,
    status TEXT DEFAULT 'New'     -- 'New', 'Investigating', 'Resolved'
);

-- Threat Intelligence Cache: caches external IP reputation lookups
CREATE TABLE IF NOT EXISTS threat_intel_cache (
    ip TEXT PRIMARY KEY,
    reputation_score INTEGER DEFAULT 0,
    total_reports INTEGER DEFAULT 0,
    country TEXT,
    isp TEXT,
    is_tor INTEGER DEFAULT 0,
    raw_data TEXT,
    last_queried DATETIME DEFAULT CURRENT_TIMESTAMP
);

-- Application Settings: key-value store for user configurations
CREATE TABLE IF NOT EXISTS settings (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL
);

-- Create performance indexes
CREATE INDEX IF NOT EXISTS idx_packets_timestamp ON packets(timestamp);
CREATE INDEX IF NOT EXISTS idx_packets_src_ip ON packets(src_ip);
CREATE INDEX IF NOT EXISTS idx_packets_dst_ip ON packets(dst_ip);
CREATE INDEX IF NOT EXISTS idx_packets_suspicious ON packets(is_suspicious);
CREATE INDEX IF NOT EXISTS idx_alerts_timestamp ON alerts(timestamp);
CREATE INDEX IF NOT EXISTS idx_alerts_severity ON alerts(severity);
CREATE INDEX IF NOT EXISTS idx_alerts_src_ip ON alerts(src_ip);
"""


class DatabaseManager:
    """Manages SQLite database connections and operations safely."""

    def __init__(self, db_path: str = "netsentry.db"):
        self.db_path = str(db_path)
        self._memory_conn = None
        if self.db_path == ":memory:":
            self._memory_conn = sqlite3.connect(":memory:", timeout=30.0, check_same_thread=False)
            self._memory_conn.row_factory = sqlite3.Row
            self._memory_conn.execute("PRAGMA foreign_keys=ON;")
        self.init_db()

    def get_connection(self) -> sqlite3.Connection:
        """Returns a configured SQLite connection with row dictionary factory."""
        if self.db_path == ":memory:" and self._memory_conn is not None:
            return self._memory_conn

        conn = sqlite3.connect(self.db_path, timeout=30.0, check_same_thread=False)
        conn.row_factory = sqlite3.Row
        # Enable Write-Ahead Logging (WAL) for concurrent read/write stability on files
        conn.execute("PRAGMA journal_mode=WAL;")
        conn.execute("PRAGMA foreign_keys=ON;")
        return conn

    @contextmanager
    def get_cursor(self):
        """Context manager for safe database transactions with auto-commit and rollback."""
        is_mem = (self.db_path == ":memory:")
        conn = self.get_connection()
        cursor = conn.cursor()
        try:
            yield cursor
            conn.commit()
        except Exception as e:
            conn.rollback()
            logger.error(f"Database transaction failed: {e}", exc_info=True)
            raise
        finally:
            cursor.close()
            if not is_mem:
                conn.close()

    def init_db(self):
        """Initializes database schema and default configuration values."""
        with self.get_cursor() as cursor:
            cursor.executescript(SCHEMA_SQL)
            # Seed default settings if not existing
            cursor.execute(
                "INSERT OR IGNORE INTO settings (key, value) VALUES ('monitoring_interface', 'default')"
            )
            cursor.execute(
                "INSERT OR IGNORE INTO settings (key, value) VALUES ('anomaly_threshold', '-0.15')"
            )
        logger.info(f"Database initialized successfully at {self.db_path}")


# Global singleton instance holder
_db_manager = None


def init_database(db_path: str) -> DatabaseManager:
    """Initializes and returns the global DatabaseManager instance."""
    global _db_manager
    _db_manager = DatabaseManager(db_path)
    return _db_manager


def get_db() -> DatabaseManager:
    """Gets the active DatabaseManager instance."""
    global _db_manager
    if _db_manager is None:
        _db_manager = DatabaseManager("netsentry.db")
    return _db_manager
